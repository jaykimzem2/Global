<script>
gsap.fromTo('#contact-hero', { y: 50, opacity: 0 }, { y: 0, opacity: 1, duration: 1, ease: 'power3.out', delay: 1.5 });

function submitContactForm(e) {
    e.preventDefault();
    const wrap    = document.getElementById('contact-form-wrap');
    const success = document.getElementById('contact-success');
    const tl = gsap.timeline();
    tl.to(wrap, { opacity: 0, y: -20, duration: 0.4,
        onComplete: () => {
            wrap.classList.add('hidden');
            success.classList.remove('hidden');
        }
    });
    tl.fromTo(success, { scale: 0.9, opacity: 0 }, { scale: 1, opacity: 1, duration: 0.5, ease: 'back.out(1.5)' });
}

function resetContactForm() {
    document.getElementById('contact-success').classList.add('hidden');
    document.getElementById('contact-form-wrap').classList.remove('hidden');
    document.getElementById('contact-form').reset();
}

// Pre-fill from URL params (from homepage CTA)
(function() {
    const params = new URLSearchParams(window.location.search);
    if (params.get('email')) {
        const emailInput = document.querySelector('input[name="email"]');
        if (emailInput) emailInput.value = params.get('email');
    }
    if (params.get('message')) {
        const msgInput = document.querySelector('textarea[name="context"]');
        if (msgInput) msgInput.value = params.get('message');
    }
})();
</script>
