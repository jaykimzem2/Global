<script>
gsap.registerPlugin(ScrollTrigger);

// ── SECTION REVEAL: TEXT fade + up ──
document.querySelectorAll('.reveal-text').forEach(el => {
    gsap.fromTo(el,
        { y: 40, opacity: 0 },
        {
            y: 0, opacity: 1, duration: 0.9, ease: 'power3.out',
            scrollTrigger: { trigger: el, start: 'top 88%', toggleActions: 'play none none none' }
        }
    );
});

// ── SECTION REVEAL: IMAGE mask + zoom ──
document.querySelectorAll('.reveal-image').forEach(el => {
    gsap.fromTo(el,
        { clipPath: 'inset(100% 0% 0% 0%)', scale: 1.1 },
        {
            clipPath: 'inset(0% 0% 0% 0%)', scale: 1, duration: 1.2, ease: 'power3.out',
            scrollTrigger: { trigger: el, start: 'top 85%', toggleActions: 'play none none none' }
        }
    );
});

// ── SECTION REVEAL: CARDS stagger ──
document.querySelectorAll('.cards-stagger').forEach(container => {
    gsap.fromTo(container.querySelectorAll('.stagger-item'),
        { y: 60, opacity: 0, scale: 0.97 },
        {
            y: 0, opacity: 1, scale: 1,
            duration: 0.9, stagger: 0.15, ease: 'power3.out',
            scrollTrigger: { trigger: container, start: 'top 80%', toggleActions: 'play none none none' }
        }
    );
});

// ── SECTION DIVIDER ──
document.querySelectorAll('.section-divider').forEach(d => {
    gsap.fromTo(d,
        { scaleX: 0, opacity: 0 },
        {
            scaleX: 1, opacity: 0.15, duration: 1.5, ease: 'power3.inOut',
            scrollTrigger: { trigger: d, start: 'top 90%', toggleActions: 'play none none none' }
        }
    );
});
</script>
